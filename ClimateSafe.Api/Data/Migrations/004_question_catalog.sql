BEGIN;

ALTER TABLE questions ADD COLUMN IF NOT EXISTS description text;

CREATE TABLE IF NOT EXISTS question_options (
    option_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id integer NOT NULL REFERENCES questions(question_id),
    option_text text NOT NULL,
    display_order integer NOT NULL CHECK (display_order > 0),
    score integer NOT NULL CHECK (score BETWEEN 0 AND 3),
    UNIQUE (question_id, display_order)
);

DO $$
BEGIN
    IF (SELECT count(*) FROM hazards WHERE hazard_id IN (1, 2, 3)) <> 3 OR
       (SELECT count(*) FROM preparedness_dimensions WHERE dimension_id IN (1, 2, 3, 4, 5)) <> 5 THEN
        RAISE EXCEPTION 'Hazard dan dimensi awal belum lengkap. Jalankan migrasi 001 terlebih dahulu.';
    END IF;
END $$;

-- ID baru mengikuti format yang digunakan oleh aplikasi desktop. Pertanyaan
-- yang sudah ada untuk hazard dan dimensi yang sama tetap dipertahankan.
WITH question_templates(dimension_id, question_template, description) AS (
    VALUES
        (1, 'Apakah kamu sudah menyiapkan perlengkapan darurat untuk menghadapi %s?', 'Termasuk tas siaga bencana (grab bag) berisi dokumen penting, senter, air minum, dan obat darurat.'),
        (2, 'Apakah kamu tahu jalur evakuasi terdekat saat terjadi %s?', 'Termasuk titik kumpul terdekat, jalur aman, dan rute alternatif dari rumah maupun tempat kerja.'),
        (3, 'Apakah kamu punya daftar kontak darurat untuk situasi %s?', 'Meliputi keluarga, tetangga, RT/RW, BPBD, puskesmas, dan layanan darurat setempat.'),
        (4, 'Apakah keluargamu punya rencana logistik menghadapi %s?', 'Termasuk air bersih, makanan tahan lama, obat rutin, dan kebutuhan khusus untuk minimal 3x24 jam.'),
        (5, 'Seberapa paham kamu langkah penyelamatan saat %s?', 'Misalnya membaca peringatan dini BMKG, mengenali tanda bahaya, dan tahu apa yang harus dilakukan.')
)
INSERT INTO questions (question_id, hazard_id, dimension_id, question_text, description)
SELECT h.hazard_id * 100 + t.dimension_id, h.hazard_id, t.dimension_id,
       format(t.question_template, lower(h.name)), t.description
FROM hazards h CROSS JOIN question_templates t
JOIN preparedness_dimensions d ON d.dimension_id = t.dimension_id
WHERE h.hazard_id IN (1, 2, 3)
ON CONFLICT (hazard_id, dimension_id) DO NOTHING;

UPDATE questions q
SET description = source.description
FROM (VALUES
    (1, 'Termasuk tas siaga bencana (grab bag) berisi dokumen penting, senter, air minum, dan obat darurat.'),
    (2, 'Termasuk titik kumpul terdekat, jalur aman, dan rute alternatif dari rumah maupun tempat kerja.'),
    (3, 'Meliputi keluarga, tetangga, RT/RW, BPBD, puskesmas, dan layanan darurat setempat.'),
    (4, 'Termasuk air bersih, makanan tahan lama, obat rutin, dan kebutuhan khusus untuk minimal 3x24 jam.'),
    (5, 'Misalnya membaca peringatan dini BMKG, mengenali tanda bahaya, dan tahu apa yang harus dilakukan.')
) AS source(dimension_id, description)
WHERE q.dimension_id = source.dimension_id AND q.hazard_id IN (1, 2, 3) AND q.description IS NULL;

WITH options(dimension_id, display_order, option_text, score) AS (
    VALUES
        (1, 1, 'Sudah lengkap dan mudah dijangkau', 3),
        (1, 2, 'Sudah ada, tetapi belum lengkap', 2),
        (1, 3, 'Baru menyiapkan beberapa barang', 1),
        (1, 4, 'Belum menyiapkan sama sekali', 0),
        (2, 1, 'Hafal jalur dan titik kumpul, sudah pernah berlatih', 3),
        (2, 2, 'Tahu jalurnya, tetapi belum pernah berlatih', 2),
        (2, 3, 'Hanya tahu sebagian jalur', 1),
        (2, 4, 'Belum tahu sama sekali', 0),
        (3, 1, 'Lengkap, tersimpan di ponsel dan dicetak', 3),
        (3, 2, 'Ada, tetapi hanya tersimpan di ponsel', 2),
        (3, 3, 'Hanya memiliki beberapa nomor', 1),
        (3, 4, 'Belum punya sama sekali', 0),
        (4, 1, 'Sudah ada untuk 3x24 jam atau lebih', 3),
        (4, 2, 'Ada, tetapi kurang dari 3x24 jam', 2),
        (4, 3, 'Baru menyiapkan sebagian kecil', 1),
        (4, 4, 'Belum ada sama sekali', 0),
        (5, 1, 'Sangat paham dan pernah berlatih', 3),
        (5, 2, 'Paham dasar-dasarnya', 2),
        (5, 3, 'Pernah mendengar, tetapi belum paham', 1),
        (5, 4, 'Belum paham sama sekali', 0)
)
INSERT INTO question_options (question_id, option_text, display_order, score)
SELECT q.question_id, o.option_text, o.display_order, o.score
FROM questions q JOIN options o ON o.dimension_id = q.dimension_id
WHERE q.hazard_id IN (1, 2, 3)
ON CONFLICT (question_id, display_order) DO NOTHING;

COMMIT;
